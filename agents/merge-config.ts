#!/usr/bin/env bun
// Print the dotagents config: the shared agents.toml with the machine's
// agents.local.toml merged on top. The local file is optional.
//
// Usage: agents/merge-config.ts SHARED LOCAL
//
// The rules follow Mise's local configs, except for arrays:
// - A value in LOCAL replaces the one in SHARED.
// - Tables merge key by key.
// - Arrays concatenate, SHARED first, without exact duplicates. This
//   includes [[skills]] and [[mcp]]: to change a shared entry, edit SHARED.

type Value = unknown;
type Table = Record<string, Value>;

const isTable = (value: Value): value is Table =>
  typeof value === "object" && value !== null && !Array.isArray(value);

function withoutDuplicates(items: Value[]): Value[] {
  return items.filter(
    (item, index) => items.findIndex((other) => Bun.deepEquals(other, item)) === index,
  );
}

function merge(shared: Value, local: Value): Value {
  if (Array.isArray(shared) && Array.isArray(local)) {
    return withoutDuplicates([...shared, ...local]);
  }
  if (isTable(shared) && isTable(local)) {
    const merged = { ...shared };
    for (const [key, value] of Object.entries(local)) {
      merged[key] = key in shared ? merge(shared[key], value) : value;
    }
    return merged;
  }
  return local;
}

const [sharedPath, localPath] = Bun.argv.slice(2);
const shared = Bun.TOML.parse(await Bun.file(sharedPath).text());
const localFile = Bun.file(localPath);
const local = (await localFile.exists()) ? Bun.TOML.parse(await localFile.text()) : {};

process.stdout.write(
  "# Generated by Mise from agents/agents.toml and agents/agents.local.toml\n" +
    "# in the dotfiles repo. Edit those files, not this one.\n\n" +
    Bun.TOML.stringify(merge(shared, local)),
);
